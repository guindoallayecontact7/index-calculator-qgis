"""Index Calculator Pro band mapping and raster harmonization readiness tools.
The harmonization algorithm audits compatibility and produces a plan/report; it does not
silently warp or resample data. Actual harmonization remains an explicit downstream step.
"""
from html import escape
import re

try:
    from qgis.core import (QgsProcessing, QgsProcessingAlgorithm, QgsProcessingParameterMultipleLayers,
                          QgsProcessingParameterEnum, QgsProcessingParameterFileDestination,
                          QgsProcessingParameterRasterLayer, QgsProcessingException)
except Exception:
    QgsProcessingAlgorithm = object

SENSORS = ['Auto-detect', 'Sentinel-2 MSI', 'Landsat 8/9 OLI']
ALIASES = {
 'BLUE': [r'\bblue\b', r'\bb02\b', r'\bb2\b', r'\bband.?2\b', r'\bcoastal\b'],
 'GREEN': [r'\bgreen\b', r'\bb03\b', r'\bb3\b', r'\bband.?3\b'],
 'RED': [r'\bred\b', r'\bb04\b', r'\bb4\b', r'\bband.?4\b'],
 'RE1': [r'\bred.?edge.?1\b', r'\bre1\b', r'\bb05\b', r'\bb5\b'],
 'RE2': [r'\bred.?edge.?2\b', r'\bre2\b', r'\bb06\b', r'\bb6\b'],
 'RE3': [r'\bred.?edge.?3\b', r'\bre3\b', r'\bb07\b', r'\bb7\b'],
 'NIR': [r'\bnir\b', r'\bb08a?\b', r'\bb08\b', r'\bb5\b', r'\bband.?8\b'],
 'SWIR1': [r'\bswir.?1\b', r'\bb11\b', r'\bb12\b', r'\bb6\b'],
 'SWIR2': [r'\bswir.?2\b', r'\bb12\b', r'\bb7\b'],
}
SENSOR_BANDS = {
 'Sentinel-2 MSI': {'BLUE':'B2','GREEN':'B3','RED':'B4','RE1':'B5','RE2':'B6','RE3':'B7','NIR':'B8/B8A','SWIR1':'B11','SWIR2':'B12'},
 'Landsat 8/9 OLI': {'BLUE':'B2','GREEN':'B3','RED':'B4','NIR':'B5','SWIR1':'B6','SWIR2':'B7'}
}

def detect_roles(text, sensor='Sensor not confidently detected'):
    name = text.lower().replace('_',' ').replace('-',' ')
    roles=[]
    # Sensor-specific band-number parsing avoids cross-sensor collisions (e.g. B5).
    match = re.search(r'\b(?:b|band\s*)?(\d{1,2})\b', name)
    if match and sensor in SENSOR_BANDS:
        band = 'B'+match.group(1)
        roles = [role for role, mapped in SENSOR_BANDS[sensor].items() if band in mapped.split('/')]
    else:
        for role, pats in ALIASES.items():
            if any(re.search(p,name,re.I) for p in pats): roles.append(role)
    return roles

def html_report(title, rows, intro=''):
    trs=''.join('<tr>'+''.join('<td>'+escape(str(c))+'</td>' for c in row)+'</tr>' for row in rows)
    return ('<!doctype html><html><head><meta charset="utf-8"><title>'+escape(title)+'</title>'
            '<style>body{font-family:Segoe UI,Arial;margin:28px;color:#222}table{border-collapse:collapse;width:100%}th,td{border:1px solid #ccc;padding:8px;text-align:left}th{background:#eee}h1{color:#285d46}</style></head><body><h1>'+escape(title)+'</h1><p>'+escape(intro)+'</p><table><thead><tr><th>Item</th><th>Detected / assessed</th><th>Notes</th></tr></thead><tbody>'+trs+'</tbody></table><p>Generated by Index Calculator Pro. Automated detection is heuristic and must be reviewed by the operator.</p></body></html>')

if QgsProcessingAlgorithm is not object:
 class AutomaticBandMappingAlgorithm(QgsProcessingAlgorithm):
    LAYERS='LAYERS'; SENSOR='SENSOR'; OUTPUT='OUTPUT'
    def name(self): return 'automatic_band_mapping'
    def displayName(self): return 'Automatic Band Mapping - Identify spectral roles'
    def group(self): return 'Bands and sensors'
    def groupId(self): return 'sensor_intelligence'
    def shortHelpString(self): return 'Heuristically maps raster layer names to spectral roles. Review the report; ambiguous names can be misidentified.'
    def createInstance(self): return AutomaticBandMappingAlgorithm()
    def initAlgorithm(self,config=None):
        self.addParameter(QgsProcessingParameterMultipleLayers(self.LAYERS,'Raster layers to inspect',layerType=QgsProcessing.SourceType.TypeRaster))
        self.addParameter(QgsProcessingParameterEnum(self.SENSOR,'Sensor profile',options=SENSORS,defaultValue=0))
        self.addParameter(QgsProcessingParameterFileDestination(self.OUTPUT,'HTML mapping report','HTML files (*.html)'))
    def processAlgorithm(self,parameters,context,feedback):
        layers=self.parameterAsLayerList(parameters,self.LAYERS,context) or []
        if not layers: raise QgsProcessingException('Select at least one raster layer.')
        si=self.parameterAsEnum(parameters,self.SENSOR,context); sensor=SENSORS[si]
        if sensor=='Auto-detect':
            names=' '.join(l.name().lower() for l in layers)
            sensor='Sentinel-2 MSI' if 'sentinel' in names or 's2' in names else ('Landsat 8/9 OLI' if 'landsat' in names or 'oli' in names else 'Sensor not confidently detected')
        rows=[]
        for layer in layers:
            roles=detect_roles(layer.name(), sensor)
            rows.append([layer.name(),', '.join(roles) or 'No role detected','Layer name-based heuristic; verify band identity and metadata.'])
        if sensor in SENSOR_BANDS:
            rows.append(['Sensor profile',sensor,'Expected band map: '+', '.join(f'{r}={b}' for r,b in SENSOR_BANDS[sensor].items())])
        else: rows.append(['Sensor profile',sensor,'Please select a sensor profile manually for band compatibility checks.'])
        output=self.parameterAsFileOutput(parameters,self.OUTPUT,context)
        with open(output,'w',encoding='utf-8') as f: f.write(html_report('Automatic Band Mapping',rows,'Maps raster layer names to likely spectral roles. This is a heuristic, not metadata-level verification.'))
        return {self.OUTPUT:output}

 class RasterHarmonizationReadinessAlgorithm(QgsProcessingAlgorithm):
    INPUTS='INPUTS'; REFERENCE='REFERENCE'; OUTPUT='OUTPUT'
    def name(self): return 'raster_harmonization_readiness'
    def displayName(self): return 'Raster Readiness and Alignment Plan'
    def group(self): return 'Bands and sensors'
    def groupId(self): return 'sensor_intelligence'
    def shortHelpString(self): return 'Compares selected rasters with a reference grid and outputs a harmonization plan. It does not resample or reproject.'
    def createInstance(self): return RasterHarmonizationReadinessAlgorithm()
    def initAlgorithm(self,config=None):
        self.addParameter(QgsProcessingParameterMultipleLayers(self.INPUTS,'Rasters to compare',layerType=QgsProcessing.SourceType.TypeRaster))
        self.addParameter(QgsProcessingParameterRasterLayer(self.REFERENCE,'Reference raster/grid'))
        self.addParameter(QgsProcessingParameterFileDestination(self.OUTPUT,'HTML harmonization report','HTML files (*.html)'))
    def processAlgorithm(self,parameters,context,feedback):
        layers=self.parameterAsLayerList(parameters,self.INPUTS,context) or []
        ref=self.parameterAsRasterLayer(parameters,self.REFERENCE,context)
        if not ref or not ref.isValid(): raise QgsProcessingException('Reference raster is invalid.')
        rows=[]
        for layer in layers:
            if not layer.isValid(): continue
            checks=[]
            if layer.crs()!=ref.crs(): checks.append('CRS differs')
            if layer.width()!=ref.width() or layer.height()!=ref.height(): checks.append('pixel dimensions differ')
            if layer.extent()!=ref.extent(): checks.append('extent differs')
            if layer.rasterUnitsPerPixelX()!=ref.rasterUnitsPerPixelX() or layer.rasterUnitsPerPixelY()!=ref.rasterUnitsPerPixelY(): checks.append('pixel size differs')
            rows.append([layer.name(),'Compatible grid' if not checks else 'Requires harmonization', '; '.join(checks) if checks else 'Matches reference CRS, extent, dimensions and pixel size'])
        rows.append(['Reference raster',ref.name(),'CRS='+ref.crs().authid()+', size='+str(ref.width())+'x'+str(ref.height())+', pixel='+str(ref.rasterUnitsPerPixelX())+' x '+str(ref.rasterUnitsPerPixelY())])
        rows.append(['Recommended next action','Explicit warp/resample/reproject','Choose method, target CRS, target resolution and resampling strategy; no data is modified by this report.'])
        output=self.parameterAsFileOutput(parameters,self.OUTPUT,context)
        with open(output,'w',encoding='utf-8') as f: f.write(html_report('Raster Harmonization Readiness',rows,'Compatibility audit against a reference grid. This report does not perform raster harmonization.'))
        return {self.OUTPUT:output}
